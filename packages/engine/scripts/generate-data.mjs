import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const data = new URL('../../../data/', import.meta.url);
const output = new URL('../src/generated/', import.meta.url);
const check = process.argv.includes('--check');

function csvFields(line) {
  if (!/^(?:"(?:[^"]|"")*"|[^",]*)(?:,(?:"(?:[^"]|"")*"|[^",]*))*$/.test(line)) {
    throw new Error('Invalid CSV row: ' + line);
  }
  return (line + ',').match(/(?:"(?:[^"]|"")*"|[^",]*),/g)
    .map(field => field.endsWith('",') ? field.slice(1, -2).replaceAll('""', '"') : field.slice(0, -1));
}

function readOffences() {
  const [heading, ...lines] = readFileSync(new URL('crosswalk/offences.csv', data), 'utf8').trimEnd().split(/\r?\n/);
  if (heading !== 'act,section,subsection,variant,title,min_years,max_years_or_life,death,life,fine_only,bns_equivalent,source_url,source_page,notes') {
    throw new Error('Unexpected offence CSV columns.');
  }
  const keys = new Set();
  return lines.map(line => {
    const fields = csvFields(line);
    const [act, section, subsection, variant, title, minimum, maximum, death, life, fineOnly, bnsEquivalent, sourceUrl, page, notes] = fields;
    const key = [act, section, subsection, variant].join(':');
    if (keys.has(key) || fields.length !== 14 || !act || !section || !title || !/^https:\/\//.test(sourceUrl)
      || !/^[1-9]\d*$/.test(page) || ![death, life, fineOnly].every(value => value === 'true' || value === 'false')) {
      throw new Error('Duplicate or invalid offence row: ' + key);
    }
    keys.add(key);
    const minYears = Number(minimum);
    const maxMonths = maximum === 'life' || maximum === 'death' ? null
      : maximum.endsWith('m') ? Number(maximum.slice(0, -1)) : Number(maximum) * 12;
    if (minimum === '' || maximum === '' || !Number.isFinite(minYears) || minYears < 0
      || (maxMonths === null ? death !== 'true' && life !== 'true'
        : !Number.isInteger(maxMonths) || maxMonths < minYears * 12 || death === 'true' || life === 'true'
          || (maxMonths === 0) !== (fineOnly === 'true'))) {
      throw new Error('Invalid offence penalty: ' + key);
    }
    return {
      act, section, subsection, variant, title, minYears, maxMonths, death: death === 'true',
      life: life === 'true', fineOnly: fineOnly === 'true', bnsEquivalent, sourceUrl, sourcePage: Number(page), notes
    };
  });
}

function generate(name, content) {
  const file = new URL(name + '.ts', output);
  const source = '// Generated by npm run generate:data. Edit the source files in data/.\n' + content + '\n';
  if (!check) writeFileSync(file, source);
  else if (readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== source) {
    throw new Error(name + '.ts is out of date. Run npm run generate:data -w @courtplus/engine.');
  }
}

if (!check) mkdirSync(output, { recursive: true });
const offences = readOffences();
generate('offences', 'export interface Offence {\n'
  + '  act: string; section: string; subsection: string; variant: string; title: string; minYears: number;\n'
  + '  maxMonths: number | null; death: boolean; life: boolean; fineOnly: boolean; bnsEquivalent: string;\n'
  + '  sourceUrl: string; sourcePage: number; notes: string;\n}\n\n'
  + 'export const offences: readonly Offence[] = [\n'
  + offences.map(row => '  ' + JSON.stringify(row) + ',').join('\n') + '\n];');
const quotes = JSON.parse(readFileSync(new URL('statutes/quotes.json', data), 'utf8'));
for (const [key, quote] of Object.entries(quotes)) {
  if (!quote.act || !quote.section || !quote.text || !/^https:\/\//.test(quote.url)) {
    throw new Error('Invalid statute entry: ' + key);
  }
}
generate('quotes', "import type { Authority } from '@courtplus/contracts';\n\n"
  + 'export const quotes = ' + JSON.stringify(quotes, null, 2) + ' satisfies Record<string, Authority>;');
